/**
 * iOS implementation of NativeBridge using cinterop bindings.
 *
 * Calls into C functions defined in relay_c_api.h:
 * - relay_create_module(): Creates a Wasm3Module from WASM bytes
 * - relay_add(): Calls the "add" function in the loaded WASM
 * - relay_set_logger(): Sets a callback for WASM log messages
 * - relay_destroy_module(): Cleans up the module
 */
actual object NativeBridge {
    private val nextId = AtomicInt(1)
    private val documents = mutableMapOf<Int, Document>()
    private val elements = mutableMapOf<Int, Element>()

    val requestHandler = staticCFunction {
            url: CPointer<ByteVar>?,
            len: UInt,
            method: UInt
        ->
        println("url: $url, len: $len, method: $method")
        val urlString = url?.readBytes(len.toInt())?.decodeToString() ?: ""
        return@staticCFunction hostEnvironment.request(urlString, HttpMethod.fromInt(method.toInt())).toUInt()
    }

    val responseBodyAsDocHandler = staticCFunction { docId: UInt ->
        return@staticCFunction hostEnvironment.responseBodyAsDoc(docId.toInt()).toUInt()
    }

    val htmlParseHandler = staticCFunction { html: CPointer<ByteVar>?, len: ULong ->
        val rawHtml = html?.readBytes(len.toInt())?.decodeToString() ?: ""
        println("[parse]")
        return@staticCFunction hostEnvironment.htmlParse(rawHtml)
    }

    val querySelectorHandler = staticCFunction { id: ULong, query: CPointer<ByteVar>?, len: ULong ->
        val selectorString = query?.readBytes(len.toInt())?.decodeToString() ?: ""

        val id = hostEnvironment.querySelector(id.toInt(), selectorString)
        if (id == -1) {
            println("[querySelector] No element found.")
            return@staticCFunction 0
        }

        return@staticCFunction id
    }

    val nodeQuerySelectorHandler = staticCFunction { id: ULong, query: CPointer<ByteVar>?, len: ULong ->
        val selectorString = query?.readBytes(len.toInt())?.decodeToString() ?: ""

        val id = hostEnvironment.nodeQuerySelector(id.toInt(), selectorString)
        if (id == -1) {
            println("[nodeQuerySelector] No element found.")
            return@staticCFunction 0
        }

        return@staticCFunction id
    }

    val querySelectorAllHandler: HostQuerySelectorAllFn = staticCFunction {
            id: ULong,
            query: CPointer<ByteVar>?,
            len: ULong,
            out_len: CPointer<UIntVar>?
        ->
        println("[querySelectorAll] Started.")
        val selectorString = query?.readBytes(len.toInt())?.decodeToString() ?: ""
        println("[querySelectorAll] $selectorString")

        val results = hostEnvironment.querySelectorAll(id.toInt(), selectorString)
        println("[querySelectorAll] $results")

        val count = results.size

        val arrayPtr = nativeHeap.allocArray<IntVar>(count)

        for (i in 0 until count) {
            arrayPtr[i] = results[i]
            println(arrayPtr[i])
        }

        out_len?.pointed?.value = count.toUInt()

        arrayPtr
    }

    val nodeTextHandler: HostNodeTextFn = staticCFunction { id, out_len ->
        val retString = hostEnvironment.nodeText(id.toInt())

        responseArena.clear()
        val responseBytes = retString.encodeToByteArray()
        val cString = nativeHeap.allocArray<ByteVar>(responseBytes.size + 1)

        for (i in responseBytes.indices) {
            cString[i] = responseBytes[i]
        }
        cString[responseBytes.size] = 0.toByte()

        out_len?.pointed?.value = responseBytes.size.toUInt()
        cString
    }

    val nodeAttrHandler: HostNodeAttrFn = staticCFunction {
        id: ULong,
        attr: CPointer<ByteVar>?,
        len: ULong,
        out_len: CPointer<UIntVar>?
        ->
        val attrString = attr?.readBytes(len.toInt())?.decodeToString() ?: ""
        val retString = hostEnvironment.nodeAttr(id.toInt(), attrString)

        responseArena.clear()
        val responseBytes = retString.encodeToByteArray()
        val cString = nativeHeap.allocArray<ByteVar>(responseBytes.size + 1)

        for (i in responseBytes.indices) {
            cString[i] = responseBytes[i]
        }
        cString[responseBytes.size] = 0.toByte()

        out_len?.pointed?.value = responseBytes.size.toUInt()
        cString
    }

    actual fun callMethod(name: String): String {
        val ptr = modulePtr ?: run {
            RelayLogger.log("RelayWASM -> callMethod: no module loaded")
            return ""
        }
        val result = relay_callMethod(ptr, name)
        return result?.toKString() ?: run {
            RelayLogger.log("RelayWASM -> callMethod '$name' returned null")
            ""
        }
    }

    /**
     * Load a WASM module from raw bytes.
     * Uses usePinned to prevent GC from moving the byte array while C is reading it.
     */
    actual fun load(bytes: ByteArray) {
        relay_set_request_handler(null)
        relay_set_html_parse_handler(null)
        relay_set_query_selector_handler(null)
        relay_set_query_selector_all_handler(null)
        relay_set_node_query_selector_handler(null)
        relay_set_node_text_handler(null)
        relay_set_node_attr_handler(null)
        relay_set_logger(null)

        modulePtr?.let {
            relay_destroy_module(it)
            modulePtr = null
        }

        bytes.usePinned { pinned ->
            modulePtr = relay_create_module(
                pinned.addressOf(0).reinterpret(),
                bytes.size.convert<size_t>()
            )
        }

        relay_set_request_handler(requestHandler)
        relay_set_response_body_as_doc_handler(responseBodyAsDocHandler)
        relay_set_html_parse_handler(htmlParseHandler)
        relay_set_query_selector_handler(querySelectorHandler)
        relay_set_query_selector_all_handler(querySelectorAllHandler)
        relay_set_node_query_selector_handler(nodeQuerySelectorHandler)
        relay_set_node_text_handler(nodeTextHandler)
        relay_set_node_attr_handler(nodeAttrHandler)

        relay_set_logger(staticCFunction { msg, len ->
            msg?.let {
                val message = it.readBytes(len.toInt()).decodeToString()
                RelayLogger.log(message)
            }
        })
    }

    /**
     * Call the "add" function in the loaded WASM module.
     * Returns 0 if no module is loaded.
     */
    actual fun add(a: Int, b: Int): Int {
        return 0
    }

